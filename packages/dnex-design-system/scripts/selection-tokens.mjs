import { readFileSync, writeFileSync } from 'node:fs';
const source = new URL('../src/tokens/selection.tokens.json', import.meta.url);
const output = new URL('../src/styles/selection.generated.css', import.meta.url);
const { selection } = JSON.parse(readFileSync(source, 'utf8'));
const cssValue = ({ $type: type, $value: value }) => {
  if (type === 'dimension' && Number.isFinite(value.value) && ['px', 'rem'].includes(value.unit)) return `${value.value}${value.unit}`;
  if (type === 'color' && value.colorSpace === 'srgb' && value.components.length === 3 && value.components.every(v => Number.isFinite(v) && v >= 0 && v <= 1) && value.alpha >= 0 && value.alpha <= 1) return `rgba(${value.components.map(v => Math.round(v * 255)).join(', ')}, ${value.alpha})`;
  throw new Error('Invalid selection token');
};
const css = `/* Generated by scripts/selection-tokens.mjs; edit selection.tokens.json. */\n:root {\n${Object.entries(selection).map(([name, token]) => `  --selection-${name}: ${cssValue(token)};`).join('\n')}\n}\n`;
if (process.argv.includes('--check')) {
  if (readFileSync(output, 'utf8') !== css) throw new Error('Selection token CSS is stale');
} else writeFileSync(output, css);
